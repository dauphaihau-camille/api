import { readFileSync } from 'node:fs';
import { EOL } from 'node:os';

const sourceFile = process.argv[2];

if (!sourceFile) {
  console.error('Usage: node scripts/generate-variables.mjs <variables-file>');
  process.exit(1);
}

const baseContent = readFileSync(sourceFile, 'utf8')
  .split(/\r?\n/)
  .filter((line) => line.trim().length > 0);

const suffix = `${Date.now()}${Math.floor(Math.random() * 1000)}`.slice(-12);
const shortSuffix = suffix.slice(-8);

const generatedValues = [
  ['smoke_suffix', shortSuffix],
  ['register_email', `hurl-smoke-${suffix}@example.com`],
  ['register_password', 'Password123!'],
  ['register_display_name', `Hurl Smoke ${shortSuffix}`],
  ['workspace_name', `Hurl Workspace ${shortSuffix}`],
  ['workspace_slug', `hurl-${shortSuffix}`],
  ['workspace_updated_name', `Hurl Workspace Updated ${shortSuffix}`],
  ['workspace_updated_slug', `hurl-upd-${shortSuffix}`],
  ['workspace_description', `Workspace smoke flow ${shortSuffix}`],
  ['workspace_updated_description', `Workspace smoke flow updated ${shortSuffix}`],
  ['document_title', `Hurl Doc ${shortSuffix}`],
  ['document_updated_title', `Hurl Doc Updated ${shortSuffix}`],
  ['document_search_query', shortSuffix],
  ['document_content_text', `Generated by Hurl smoke ${shortSuffix}`],
];

for (const [key, value] of generatedValues) {
  baseContent.push(`${key}=${value}`);
}

process.stdout.write(`${baseContent.join(EOL)}${EOL}`);
